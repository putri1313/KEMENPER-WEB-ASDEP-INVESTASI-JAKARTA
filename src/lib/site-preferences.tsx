type Preferences = {
  theme: SiteTheme;
  language: SiteLanguage;
  setTheme: (theme: SiteTheme) => void;
  setLanguage: (language: SiteLanguage) => void;
  t: (english: string) => string;
};

const reportedMissingTranslations = new Set<string>();

const PreferencesContext = createContext<Preferences | null>(null);

export function SitePreferencesProvider({ children }: { children: ReactNode }) {
  const [theme, setTheme] = useState<SiteTheme>("light");
  const [language, setLanguage] = useState<SiteLanguage>("en");

  useEffect(() => {
    const savedTheme = localStorage.getItem("kemenpar-theme");
    const savedLanguage = localStorage.getItem("kemenpar-language");
    if (savedTheme === "light" || savedTheme === "dark") setTheme(savedTheme);
    if (savedLanguage === "en" || savedLanguage === "id") setLanguage(savedLanguage);
  }, []);

  useEffect(() => {
    document.documentElement.dataset["theme"] = theme;
    document.documentElement.style.colorScheme = theme;
    localStorage.setItem("kemenpar-theme", theme);
  }, [theme]);

  useEffect(() => {
    document.documentElement.lang = language;
    localStorage.setItem("kemenpar-language", language);
  }, [language]);

  const value = useMemo(() => {
    const t = (english: string) => {
      if (language === "en") return english;
      const translation = translations[english];
      if (translation) return translation;
      if (import.meta.env?.DEV && !reportedMissingTranslations.has(english)) {
        reportedMissingTranslations.add(english);
        console.warn(`[i18n] Indonesian translation missing: ${english}`);
      }
      return english;
    };
    return { theme, language, setTheme, setLanguage, t };
  }, [theme, language]);
  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function useSitePreferences() {
  const value = useContext(PreferencesContext);
  if (!value) throw new Error("useSitePreferences must be used within SitePreferencesProvider");
  return value;
}
